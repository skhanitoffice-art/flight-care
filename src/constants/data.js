export const getAddonAsset = (id) => {
  if (!id) return null;
  const key = String(id).trim().toLowerCase();
  if (ADDON_ASSETS[key]) return ADDON_ASSETS[key];
  if (key.includes('wheel')) return ADDON_ASSETS.wheel;
  if (key.includes('wrap') || key.includes('luggage')) return ADDON_ASSETS.wrap;
  if (key.includes('transfer') || key.includes('car') || key.includes('pickup') || key.includes('rent') || key.includes('dropoff') || key.includes('vehicle')) return ADDON_ASSETS.transfer;
  if (key.includes('visa')) return ADDON_ASSETS.visa;
  if (key.includes('photocopy')) return ADDON_ASSETS.photocopy;
  if (key.includes('print')) return ADDON_ASSETS.print;
  if (key.includes('money') || key.includes('curr') || key.includes('cash') || key.includes('exchange')) return ADDON_ASSETS.money;
  if (key.includes('hotel') || key.includes('room') || key.includes('stay')) return ADDON_ASSETS.hotel;
  if (key.includes('food') || key.includes('meal') || key.includes('dining')) return ADDON_ASSETS.food;
  if (key.includes('medic') || key.includes('ambul') || key.includes('doctor')) return ADDON_ASSETS.medical;
  if (key.includes('tour') || key.includes('guide')) return ADDON_ASSETS.tour;
  if (key.includes('secur') || key.includes('guard') || key.includes('protocol')) return ADDON_ASSETS.security;
  return null;
};


